/**
 * Copies text to the clipboard. Returns false if the browser refused.
 *
 * navigator.clipboard only exists in a "secure context" (https or localhost).
 * Opening the dev site from a phone as http://192.168.x.x is NOT one, so the
 * modern API is undefined there - fall back to the old execCommand route.
 */
export async function copyText(text: string): Promise<boolean> {
  try {
    if (navigator.clipboard && window.isSecureContext) {
      await navigator.clipboard.writeText(text);
      return true;
    }
  } catch {
    // permission denied etc. - try the legacy path below
  }

  const area = document.createElement("textarea");
  area.value = text;
  area.setAttribute("readonly", "");
  area.style.position = "fixed";
  area.style.top = "0";
  area.style.opacity = "0";
  document.body.appendChild(area);
  area.select();
  area.setSelectionRange(0, text.length);
  let ok = false;
  try {
    ok = document.execCommand("copy");
  } catch {
    ok = false;
  }
  document.body.removeChild(area);
  return ok;
}
